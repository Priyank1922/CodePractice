package DSA;

public class RelationalOperator {
	public static void main(String[] args) {
		int p = 10;
		int q = 15;

		 System.out.println("Is equal to ::" + (p == q));
		System.out.println("Is not Equal to::" + (p != q));
		System.out.println("Greater then::" + (p > q));
		System.out.println("Smaller then::" + (p < q));
		System.out.println("Greater and Equal to::" + (p >= q));
		System.out.println("Smaller then and equal to::" + (p <= q));

	}
}